import { readFile, writeFile, access } from "node:fs/promises";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "..");
const seen = new Set();
async function visit(url) {
  const key = url.pathname + url.search;
  if (seen.has(key)) return;
  seen.add(key);
  const file = path.join(root, url.pathname);
  await access(file);
  if (!/\.(html|js|css|webmanifest)$/.test(url.pathname)) return;
  const text = await readFile(file, "utf8");
  const refs = [...text.matchAll(/(?:\bfrom\s*|\bimport\s*\(?\s*|(?:src|href)=)["']([^"']+)["']/g)].map(m => m[1]);
  refs.push(...[...text.matchAll(/url\(["']?([^"')]+)["']?\)/g)].map(m => m[1]));
  if (url.pathname.endsWith(".webmanifest")) refs.push(...JSON.parse(text).icons.map(i => i.src));
  for (const ref of refs) {
    if (/^(?:https?:|data:|#)/.test(ref)) continue;
    const next = new URL(ref, url);
    if (!/\.(html|js|css|webmanifest|svg|png|woff2?)$/.test(next.pathname)) continue;
    await visit(next);
  }
}
for (const file of ["/next/index.html", "/index.html", "/manifest.webmanifest", "/material-web.bundle.js", "/icons/icon-192.png", "/icons/icon-512.png"]) await visit(new URL(file, "https://pincon.app"));
const output = `// Generated by automation/build-next-precache.mjs. Bump sw.js version when rebuilding.\nconst PINCON_APP_SHELL = ${JSON.stringify([...seen].sort(), null, 2)};\n`;
await writeFile(path.join(root, "next/precache-manifest.js"), output);
console.log(`Next precache: ${seen.size} assets`);
